# Cuts the best takes from raw.wav, processes them, places them on the film timeline,
# and writes timings + waveform envelopes for the animations.
import numpy as np, subprocess, wave, json, os
D=os.path.dirname(os.path.abspath(__file__)); R=os.path.dirname(D); SR=48000
def rd(p):
    w=wave.open(p); return np.frombuffer(w.readframes(w.getnframes()),'<i2').astype(float)/32768.0
def wr(p,x):
    w=wave.open(p,'wb'); w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(x,-1,1)*32767).astype('<i2').tobytes()); w.close()
raw=rd(D+'/raw.wav')
CLEAN="highpass=f=90,afftdn=nf=-30:nr=14,equalizer=f=250:t=q:w=1:g=-2,equalizer=f=3200:t=q:w=1.2:g=5,acompressor=threshold=-20dB:ratio=3:attack=5:release=90:makeup=2,alimiter=limit=0.9"
PHONE="highpass=f=320,lowpass=f=3400,afftdn=nf=-30:nr=14,equalizer=f=1600:t=q:w=1:g=4,acompressor=threshold=-22dB:ratio=4:attack=3:release=60:makeup=3,alimiter=limit=0.9"
def proc(x,flt):
    wr(D+'/_in.wav',x); subprocess.run(['ffmpeg','-y','-loglevel','error','-i',D+'/_in.wav','-af',flt,'-ar',str(SR),D+'/_out.wav'],check=True); return rd(D+'/_out.wav')[:len(x)]
def cut(a,b,f=0.012):
    x=raw[int(a*SR):int(b*SR)].copy(); n=int(f*SR); r=np.linspace(0,1,n); x[:n]*=r; x[-n:]*=r[::-1]; return x
def join(parts,xf=0.03):
    out=parts[0]; n=int(xf*SR)
    for p in parts[1:]:
        r=np.linspace(0,1,n); out=np.concatenate([out[:-n],out[-n:]*r[::-1]+p[:n]*r,p[n:]])
    return out
# ---- edit decisions (raw seconds -> film seconds) ----
C1=(0.62,2.88,4.55); F1=(3.84,6.97,7.15); C2a=(7.76,8.42,10.40)
C2b_parts=[(9.10,11.45),(11.75,13.22)]; C2b_start=11.30
SETS_RAW=12.52   # start of "sets" -> the phone filter opens here
FZ=None
ACT1_LEN_BASE=17.5
# words (raw times) for captions
W_C1=[('How',0.70),('far?',0.95),('We',1.80),('still',1.97),('dey',2.17),('go',2.29),('that',2.44),('party?',2.60)]
W_F1=[('Omo,',3.90),('I',4.90),('no',5.34),('get',5.45),('wetin',5.62),('to',5.88),('wear',6.10),('o.',6.32)]
W_C2a=[('Oya',7.82),('na,',8.00)]
W_C2b=[('make',9.16),('I',9.28),('find',9.52),('you',9.80),('one',10.02),('of',10.76),('my',11.14),('new',12.00),('sets.',12.52)]
def c2b_map(r): return C2b_start+(r-9.10) if r<11.45 else C2b_start+(11.45-9.10)+(r-11.75)
FZ=round(c2b_map(13.16),2)
DSH=FZ-12.3; G=17.5+DSH
# CTA (friend_2, take 2): raw 19.10-22.00 placed at act2 local cta0
CTA_RAW=(19.10,22.00); CTA0_LOCAL=16.3
W_F2=[('Wetin',19.30),('you',19.84),('dey',20.00),('wait',20.22),('for?',20.46),('Go',20.96),('get',21.15),('your',21.36),('own',21.52),('now!',21.66)]
TOTAL=G+16.3+3.3+4.6
film=np.zeros(int(TOTAL*SR)); dry=np.zeros_like(film)
def place(x,t,buf):
    i=int(t*SR); buf[i:i+len(x)]+=x[:len(buf)-i]
# Collins 1 (phone)
x=cut(*C1[:2]); place(proc(x,PHONE),C1[2],film); place(x,C1[2],dry)
# Friend 1 (clean, local)
x=cut(*F1[:2]); place(proc(x,CLEAN),F1[2],film); place(x,F1[2],dry)
# Collins 2a (phone)
x=cut(*C2a[:2]); place(proc(x,PHONE),C2a[2],film); place(x,C2a[2],dry)
# Collins 2b: phone, then "sets" opens up to full voice with a short tail
x=join([cut(a,b) for a,b in C2b_parts])
ph=proc(x,PHONE); cl=proc(x,CLEAN+",aecho=0.8:0.55:70|140:0.22|0.12")
k=int((c2b_map(SETS_RAW)-C2b_start)*SR); n=int(0.1*SR); m=np.ones(len(x)); m[k:]=0; m[k:k+n]=np.linspace(1,0,n)
y=ph*m+cl*(1-m)*1.15
tail=np.zeros(int(0.6*SR)); y=np.concatenate([y,tail])
place(y,C2b_start,film); place(x,C2b_start,dry)
# Friend 2 (clean)
x=cut(*CTA_RAW); t_cta=G+CTA0_LOCAL; place(proc(x,CLEAN),t_cta,film); place(x,t_cta,dry)
film/=max(1e-9,np.abs(film).max()); film*=0.95
wr(D+'/vo_track.wav',film)
# envelopes at 100 Hz (from the dry voice)
h=SR//100; env=np.array([np.sqrt(np.mean(dry[i:i+h]**2)) for i in range(0,len(dry)-h,h)])
env=np.clip(20*np.log10(env+1e-9),-50,0); env=(env+50)/50; env=np.clip((env-0.25)/0.6,0,1)
json.dump([round(float(v),3) for v in env[:int(G*100)+50]],open(R+'/act1/env.json','w'))
json.dump([round(float(v),3) for v in env[int(G*100):]],open(R+'/act2/env2.json','w'))
# timings
wds=[{'s':'C','w':w,'t':round(C1[2]+(r-C1[0]),2),'d':0.18} for w,r in W_C1]
wds+=[{'s':'F','w':w,'t':round(F1[2]+(r-F1[0]),2),'d':0.18} for w,r in W_F1]
wds+=[{'s':'C','w':w,'t':round(C2a[2]+(r-C2a[0]),2),'d':0.18} for w,r in W_C2a]
wds+=[{'s':'C','w':w,'t':round(c2b_map(r),2),'d':0.18} for w,r in W_C2b]
tim={'_note':'Real VO timings (seconds, film time). Generated by vo/build_vo.py','segments':{'C1':[4.5,6.85],'F1':[7.1,10.3],'C2':[10.35,FZ]},'freeze':FZ,'connect':4.0,'words':wds}
json.dump(tim,open(R+'/act1/timings.json','w'),indent=1)
cta=[{'w':w,'o':round(r-CTA_RAW[0],2)} for w,r in W_F2]
json.dump({'G':round(G,2),'total':round(TOTAL,2),'cta':cta},open(D+'/cta.json','w'),indent=1)
print('FZ',FZ,'G',round(G,2),'TOTAL',round(TOTAL,2)); print([ (c['w'],c['o']) for c in cta])
